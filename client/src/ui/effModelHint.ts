// Что показывать про вариант модели, включившийся сам по референсам.
//
// ⚠️ Подсказка стоит ВПЛОТНУЮ к выпадающему списку, где имя модели уже
// написано, а имена вариантов в каталоге строятся как «<модель> — <вариант>».
// Получалось «Seedream 5.0 Pro» и тут же рядом «включена «Seedream 5.0 Pro —
// по референсам»» — одно и то же имя дважды подряд. Это не только шум: ряд
// с параметрами из-за длины переносился на следующую строку (жалоба
// 22.08.2026), то есть лишний текст выталкивал с глаз рабочие элементы.
//
// Показываем то, чем вариант ОТЛИЧАЕТСЯ. Полное имя не теряется — оно уходит
// в подсказку при наведении.

const РАЗДЕЛИТЕЛЬ = ' — '

/**
 * Хвост имени варианта после имени базовой модели.
 *
 * Имя без общего начала возвращается целиком: у части моделей вариант назван
 * не по этому правилу («Grok Image» → «Grok Image Edit»), и обрезать там
 * нечего — лучше показать полное имя, чем огрызок.
 */
export function effModelSuffix(baseName: string, effName: string): string {
  const начало = baseName + РАЗДЕЛИТЕЛЬ
  if (!effName.startsWith(начало)) return effName
  const хвост = effName.slice(начало.length).trim()
  return хвост || effName
}

/** Полное имя для подсказки при наведении: короткий текст не должен прятать его. */
export function effModelTitle(explanation: string, effName: string): string {
  return `${explanation}: ${effName}`
}
