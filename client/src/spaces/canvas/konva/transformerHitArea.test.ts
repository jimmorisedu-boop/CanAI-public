import assert from 'node:assert/strict'
import fs from 'node:fs'
import test from 'node:test'

const source = fs.readFileSync(new URL('./KonvaCanvas.tsx', import.meta.url), 'utf8')

/**
 * ⚠️ Промах мимо угловой ручки стоил человеку всего выделения.
 *
 * Жалоба 19.09.2026 с записью экрана («не хочет увеличивать видео»): на мелком
 * выделении угол не давался вовсе. Замер в живом холсте: ручка 9×9 ловит
 * нажатие в ±3 px от центра, а промах на четыре пикселя уходит в ПУСТОЙ холст —
 * то есть начинает рамку выделения и стирает всё, что человек набрал. Он тянул
 * угол снова и снова и каждый раз терял набранное.
 *
 * Лечение — невидимый запас вокруг ручки (Konva рисует его в карту попаданий
 * поверх самой ручки). Проверено A/B настоящей мышью в живом приложении: с
 * запасом тяга в 6 px от центра хватает ручку и объекты растут 70 → 129, без
 * запаса тот же жест не делает ничего.
 *
 * ⚠️ Саму ручку на экране НЕ растим: девять пикселей — это вид, и он не
 * виноват. Растёт только зона попадания.
 */
test('у ручек трансформера есть невидимый запас попадания', () => {
  assert.match(
    source,
    /anchorStyleFunc=\{\(anchor\) => \{ anchor\.hitStrokeWidth\(ANCHOR_HIT_STROKE\) \}\}/u,
    'запас ставится через штатный хук Konva, иначе он слетит при обновлении трансформера',
  )

  const size = Number(/anchorSize=\{(\d+)\}/u.exec(source)?.[1])
  const hit = Number(/const ANCHOR_HIT_STROKE = (\d+)/u.exec(source)?.[1])
  assert.ok(Number.isFinite(size) && Number.isFinite(hit), 'оба числа должны быть видны в исходнике')
  // Запас должен быть ощутимо шире самой ручки — иначе он ничего не меняет.
  assert.ok(hit >= size * 2, `запас ${hit} мал против ручки ${size}`)
})
