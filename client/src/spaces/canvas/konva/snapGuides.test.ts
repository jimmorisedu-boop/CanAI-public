// ⚠️ ЗАЧЕМ ЭТОТ ФАЙЛ. Правило «к чему липнет выделение» живёт в
// applySnapGuides, и до 26.08.2026 на неё не было НИ ОДНОГО теста. Соседи при
// этом покрыты плотно: snapMath проверяет арифметику, groupDrag — перенос. Из-за
// этого прогон оставался зелёным при любом варианте правила, и две жалобы
// months подряд чинили одну и ту же ручку в разные стороны:
//
//   18.08.2026 — «тянешь стопку за среднюю картинку, а стопка встаёт мимо»
//                → якорем сделали общую рамку группы;
//   26.08.2026 — «при движении нескольких единиц выравнивание исчезает»
//                → общая рамка почти ни с чем не совпадает на разноразмерном
//                  материале (замер: у одного объекта направляющая видна в 31%
//                  положений, у двух — в 11%).
//
// Теперь якоря ОБА, побеждает ближайший. Тесты ниже закрепляют оба сценария
// сразу — чтобы починка одного не могла молча сломать другой.

;(globalThis as { requestAnimationFrame?: unknown }).requestAnimationFrame ??=
  ((cb: () => void) => setTimeout(cb, 0)) as typeof requestAnimationFrame

function board(items: Array<{ id: string; x: number; y: number; w: number; h: number }>): CanvasStore {
  const store = new CanvasStore()
  for (const item of items) {
    store.addItem({ ...item, kind: 'text', text: 'x' } as unknown as CanvasItem)
  }
  return store
}

/** Konva-ноде здесь нужны только координаты. */
function node(x: number, y: number) {
  let pos = { x, y }
  return {
    x: () => pos.x,
    y: () => pos.y,
    position: (next?: { x: number; y: number }) => {
      if (next) pos = next
      return pos
    },
  }
}

function drag(store: CanvasStore, id: string, dx: number, dy: number) {
  // заглушки генерации живут отдельно от items — они тоже перетаскиваются
  const item = store.getItem(id) ?? store.getPending().find((p) => p.id === id)!
  const handle = node(item.x + dx, item.y + dy)
  applySnapGuides(store, id, handle as never)
  return { guides: store.getGuides(), at: handle.position() }
}

test('одиночный перенос липнет краем и показывает направляющую', () => {
  const store = board([
    { id: 'a', x: 0, y: 0, w: 100, h: 100 },
    { id: 'b', x: 0, y: 300, w: 100, h: 100 },
  ])
  store.setSelection(['a'])

  const { guides, at } = drag(store, 'a', 4, 0)
  assert.equal(at.x, 0, 'край обязан прилипнуть к краю соседа')
  assert.ok(guides.length > 0, 'без направляющей человек не поймёт, к чему прилипло')
})

// Жалоба 18.08.2026: тянешь стопку за среднюю картинку — прилипнуть должна
// СТОПКА. Здесь совпадает только центр общей рамки, ни один объект сам по себе
// с соседом не выравнивается.
test('группа липнет ОБЩЕЙ рамкой, когда совпадает именно она', () => {
  const store = board([
    { id: 'a', x: 0, y: 0, w: 100, h: 100 },
    { id: 'c', x: 400, y: 0, w: 100, h: 100 },
    // край соседа стоит ровно на центре общей рамки (0..500 → 250)
    { id: 'other', x: 250, y: 600, w: 100, h: 100 },
  ])
  store.setSelection(['a', 'c'])

  const { guides } = drag(store, 'a', 0, 0)
  assert.ok(guides.length > 0, 'общая рамка обязана оставаться якорем')
  assert.equal(guides[0]![0], 250, 'направляющая рисуется там, где совпало')
})

// Жалоба 26.08.2026: общая рамка — фигура, которой на доске нет, и на
// разноразмерном материале её края почти ни с чем не совпадают. Если якорем
// остаётся только она, направляющие пропадают. Здесь совпадает край ОДНОГО
// движимого объекта, а общая рамка не совпадает ни с чем.
test('группа липнет и ОТДЕЛЬНЫМ объектом, когда совпадает он', () => {
  const store = board([
    { id: 'a', x: 0, y: 0, w: 100, h: 100 },
    { id: 'c', x: 330, y: 0, w: 100, h: 100 },
    // 380 — центр объекта c; края общей рамки (0, 215, 430) сюда не попадают
    { id: 'other', x: 380, y: 600, w: 40, h: 100 },
  ])
  store.setSelection(['a', 'c'])

  const { guides } = drag(store, 'a', 0, 0)
  assert.ok(
    guides.length > 0,
    'до починки здесь направляющих не было вовсе — ровно это и жаловались',
  )
  assert.equal(guides[0]![0], 380, 'направляющая обязана стоять на совпавшем крае')
})

