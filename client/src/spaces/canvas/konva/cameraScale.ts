// Масштаб камеры для декораций фигуры — огрублённый.
//
// Отдельный модуль без Konva: его тянет itemHelpers, а в Node этот импорт
// требует нативный пакет, и чистую функцию иначе было бы нечем проверить.
//
// Огрубление до четвертей октавы (шаг ~19%). Точное значение здесь незачем:
// единственные потребители держат по нему МИНИМАЛЬНЫЙ размер на экране — 3px
// у полоски промпта, 12px у метки. Ошибка в 19% там меньше половины пикселя,
// глазом не видна. Зато плавный зум перестаёт быть чередой из десятков
// перерисовок: на всём пути от 100% до 6% таких ступеней около двадцати.
export function quantizeScale(scale: number): number {
  if (!Number.isFinite(scale) || scale <= 0) return 1
  return 2 ** (Math.round(Math.log2(scale) * 4) / 4)
}
