import type { CanvasStore } from './canvasStore'

/**
 * Довести жест до записи в холст, добрав аренду, если она ещё в пути.
 *
 * ⚠️ **Откат вместо ожидания и есть «перестал переноситься контент»**
 * (жалоба 09.09.2026). Жест на сетевой доске устроен так: свободный объект
 * ведём СРАЗУ, а аренду просим параллельно — иначе объект не трогался бы с
 * места, пока палец уже едет (это чинили 08.09.2026). Но фиксацию оставили
 * прежней: `canMutateItems` отвечал «нет», пока ответ сервера в пути, и
 * `onDragEnd` откатывал объект на исходное место. Круг до сервера команды —
 * 300 мс по живому соединению и больше секунды по холодному, а обычный
 * перенос короче: человек вёл картинку, отпускал, и она прыгала обратно.
 *
 * Ровно то же ломало изменение размера (`onTransformEnd`) и правку текста.
 *
 * Правило: жест над объектом, которого НИКТО не держит, обязан доехать до
 * холста. Аренда — доказательство единоличной правки, а не право писать (то
 * проверено раньше, при открытии сессии), поэтому её можно добрать после
 * жеста: пока ответ идёт, Konva-нода стоит на новом месте, и человек не видит
 * ни прыжка, ни задержки. Откатываем только там, где объект держит ЖИВОЙ
 * коллега или сервер аренду не дал: тогда прыжок честен — правка и правда не
 * состоялась.
 *
 * ⚠️ Когда аренда уже в руках — а на локальной доске она не нужна вовсе —
 * работа идёт СИНХРОННО: иначе перенос на локальной доске стал бы отложенным,
 * а история отмены — гонкой с микрозадачами.
 */
export function commitGestureWithLease(
  store: Pick<CanvasStore, 'canMutateItems' | 'looksEditable' | 'withSelection'>,
  ids: readonly string[],
  commit: () => void,
  revert: () => void,
): void {
  const list = [...ids]
  if (store.canMutateItems(list)) {
    commit()
    return
  }
  // Объект держит живой коллега: ждать нечего, аренды не будет.
  if (!store.looksEditable(list)) {
    revert()
    return
  }
  void store.withSelection(list, commit).then((admitted) => {
    if (!admitted) revert()
  })
}
