/**
 * Куда ставить подпись кнопки, нарисованной на холсте.
 *
 * ⚠️ И `verticalAlign="middle"`, и наивное `(height - fontSize) / 2` ставят
 * подпись ВЫШЕ середины кнопки — это и было видно на карточках генерации
 * (жалоба 07.09.2026). Konva рисует строку с `textBaseline: middle`, а он
 * центрирует кегельную площадку целиком, вместе с местом под хвосты букв.
 * Глаз же считает серединой строки середину между верхом заглавной и базовой
 * линией, а она ВЫШЕ середины площадки.
 *
 * Поправка замерена в браузере на Onest (по «П», при `textBaseline: middle`):
 * оптический центр лежит на 0.102–0.124 кегля выше точки рисования при
 * размерах 11, 13 и 16 px. Отсюда 0.11 — значит точку рисования опускаем на
 * столько же, и подпись садится ровно посередине.
 */
export const OPTICAL_CENTRE_SHIFT = 0.11

export function cardActionLabelY(height: number, fontSize: number): number {
  // Konva смещает строку на половину её высоты вниз от заданного y, поэтому
  // здесь возвращается ВЕРХ строки, а не точка рисования.
  return height / 2 - fontSize / 2 + OPTICAL_CENTRE_SHIFT * fontSize
}
