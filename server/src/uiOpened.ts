// Дошёл ли браузер до интерфейса.
//
// ⚠️ Лаунчер открывает адрес и до сих пор просто ВЕРИЛ, что браузер его
// открыл. Chrome с несколькими профилями показывает «Who's using Chrome?» и
// открытый адрес при этом теряет: приложение работает, порт слушает, а человек
// смотрит на выбор профиля и видит, что «канвас не открылся сам» (09.09.2026).
// Отметка — самый дешёвый способ отличить «браузер пришёл» от «браузер не
// пришёл»: по ней лаунчер повторяет попытку и, если и она не удалась, называет
// адрес словами вместо того, чтобы молчать.
//
// Больше ни на что она не влияет и никуда не пишется: это флажок на время
// жизни процесса.

let opened = false

/** Запрос страницы интерфейса. Зовётся из раздачи собранного клиента. */
export function markUiOpened(): void {
  opened = true
}

export function uiOpened(): boolean {
  return opened
}

/**
 * ⚠️ **Живая вкладка — это не то же самое, что «страницу когда-то просили».**
 *
 * Отметка выше живёт в памяти процесса и при перезапуске обнуляется. Дальше
 * получалось так: сервер поднимается заново, лаунчер видит «интерфейс никто не
 * открывал» и открывает ВТОРУЮ вкладку — а первая у человека никуда не делась.
 * Две вкладки на одной доске, присутствие после перезапуска пустое (оно тоже в
 * памяти), обе считают доску своей, и первая же запись проигравшей становится
 * КОНФЛИКТНОЙ КОПИЕЙ. На записи экрана 20.09.2026 это выглядит так: доска
 * мгновенно исчезает, а вместо неё карточка «Обе версии сохранены» — через две
 * с половиной минуты после перезапуска, ровно когда доехала генерация и
 * случилась первая запись.
 *
 * Живую вкладку видно по опросу состояния: его шлёт каждая открытая страница
 * (serverStatusMonitor). ⚠️ Браузер отличаем от самого лаунчера по заголовкам
 * sec-fetch-*: их ставит браузер и не ставит никто другой. Сверять по имени
 * программы было бы гаданием.
 */
const UI_ALIVE_MS = 15_000
let lastBrowserPoll = 0

/** Запрос состояния пришёл из браузера — значит вкладка открыта прямо сейчас. */
export function markBrowserPoll(now = Date.now()): void {
  lastBrowserPoll = now
}

export function uiAlive(now = Date.now()): boolean {
  return lastBrowserPoll > 0 && now - lastBrowserPoll < UI_ALIVE_MS
}

/**
 * ⚠️ Признак — РОВНО `sec-fetch-site`, и только он.
 *
 * Сперва я брал ещё и `sec-fetch-mode` — и промахнулся: замер показал, что
 * `fetch` в самом Node тоже его ставит (`sec-fetch-mode: cors`), а значит за
 * вкладку сошёл бы любой наш внутренний запрос. `sec-fetch-site` присылает
 * браузер и не присылают ни Node, ни PowerShell лаунчера — проверено обоими.
 */
export function looksLikeBrowser(headers: {
  get(name: string): string | null | undefined
}): boolean {
  return Boolean(headers.get('sec-fetch-site'))
}

/** Для тестов: вернуть модуль в исходное состояние. */
export function resetUiSigns(): void {
  opened = false
  lastBrowserPoll = 0
}
