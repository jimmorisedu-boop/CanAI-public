import assert from 'node:assert/strict'
import test from 'node:test'
import { salvagePrompts } from './promptChatSalvage.js'
import { parsePromptChatResponse } from './promptChatResponse.js'

// Форма из жалобы 18.09.2026: человек попросил пять промптов, модель бросила
// конверт и написала их разметкой — карточек с кнопками не появилось вовсе.
const FIVE_PROMPTS = `Вот пять вариантов.

1. **Реалистичный студийный портрет**
Фотореалистичный портрет 13-летнего мальчика с небольшим лишним весом, мягкое округлое лицо, тёмные густые волнистые волосы, добрый уверенный взгляд в камеру, серая худи, яркий однотонный розовый фон, 85mm portrait photography.

2. **Светловолосый подросток в естественном свете**
Фотореалистичный портрет мальчика-подростка 13 лет, слегка полноватое телосложение, светло-русые растрёпанные волосы, веснушки на носу и щеках, белая футболка, нейтральный бежево-серый фон, editorial teen portrait.

3. **Современный fashion-портрет**
Стильный реалистичный портрет 13-летнего мальчика, русые волосы с мелированными светлыми прядями, объёмная небрежная укладка, чёрная рубашка, тёплый бежевый студийный фон, high-end editorial photography.

4. **Уличное селфи на закате**
Реалистичный селфи-портрет мальчика 13 лет с лёгкой полнотой, округлые щёки, каштановые взъерошенные волосы, голубое небо и далёкий городской пейзаж на фоне, мягкий вечерний солнечный свет, natural colors.

5. **Кинематографичный портрет с цветным светом**
Крупный кинематографичный портрет подростка-мальчика 13 лет, тёмно-русые кудрявые волосы, приглушённый интерьер спальни, фиолетово-синяя неоновая подсветка, атмосферные тени, intimate teenage portrait.`

test('пять промптов текстом превращаются в пять карточек', () => {
  const found = salvagePrompts(FIVE_PROMPTS)
  assert.equal(found.length, 5)
  assert.equal(found[0].title, 'Реалистичный студийный портрет')
  assert.match(found[0].prompt, /85mm portrait photography/)
  assert.equal(found[4].title, 'Кинематографичный портрет с цветным светом')
  // Разметка в карточку не переезжает.
  assert.equal(found.some((item) => item.title.includes('*') || item.prompt.includes('**')), false)
})

test('обычный ответ карточками НЕ становится', () => {
  // ⚠️ Ровно та беда, ради которой признак сделан узким: когда-то на этот
  // вопрос приходила карточка «Готовый промпт: два плюс два будет четыре».
  assert.deepEqual(salvagePrompts('Два плюс два будет четыре.'), [])
  assert.deepEqual(salvagePrompts(''), [])
  assert.deepEqual(salvagePrompts('Понял задачу. Давай уточню: какой формат кадра нужен — вертикальный или горизонтальный? От этого зависит композиция и то, как встанет фон.'), [])
})

test('один блок — это ещё не список', () => {
  // Меньше двух блоков считаем обычным ответом: так узкий признак не
  // превращается в «любой длинный текст с заголовком».
  const single = `Вот идея.

**Студийный портрет**
Фотореалистичный портрет подростка, мягкий студийный свет, серый фон, 85mm, высокая детализация кожи, спокойный взгляд в камеру, натуральные цвета.`
  assert.deepEqual(salvagePrompts(single), [])
})

test('короткие пункты списка промптами не считаются', () => {
  const shortList = `Что учесть:

1. **Свет**
Мягкий.

2. **Фон**
Однотонный.`
  assert.deepEqual(salvagePrompts(shortList), [])
})

test('разбор ответа целиком отдаёт карточки, не трогая текст', () => {
  const parsed = parsePromptChatResponse(FIVE_PROMPTS)
  assert.equal(parsed.prompts.length, 5)
  // ⚠️ Текст остаётся как был: ошибись разбор — человек ничего не теряет.
  assert.match(parsed.reply, /Вот пять вариантов/)
})

test('правильный конверт с пятью промптами больше не теряет пятый', () => {
  // ⚠️ Потолок был 4 и спорил с человеком: на просьбу «напиши 5 промптов»
  // пятый молча пропадал по дороге.
  const envelope = JSON.stringify({
    reply: 'Готово',
    prompts: Array.from({ length: 5 }, (_, index) => ({
      title: `Вариант ${index + 1}`,
      prompt: `Фотореалистичный портрет, вариант ${index + 1}, мягкий свет, 85mm`,
    })),
  })
  assert.equal(parsePromptChatResponse(envelope).prompts.length, 5)
})
