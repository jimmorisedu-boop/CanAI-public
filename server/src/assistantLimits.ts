// Пределы помощника своей доски и резка текста по знакам.

/** Название помощника. Столько же у помощника сетевой доски. */
export const MAX_NAME_CHARS = 80
/** Название документа знаний. */
export const MAX_DOC_NAME_CHARS = 120

/**
 * Сколько знаков инструкций хранит помощник.
 *
 * ⚠️ Столько же, сколько у помощника сетевой доски (сервер команды, `fields` в
 * assistants/profiles.ts). Раньше здесь было 20 000 против 24 000 там, и
 * помощник, перенесённый файлом с сетевой доски на свою, молча терял хвост
 * инструкций — «тот же самый, только поглупел». Меняется предел сервера
 * команды — менять и этот. То же число держит окно правки помощника; за
 * обоими следит сторож в assistantsExchange.test.ts.
 */
export const MAX_INSTRUCTIONS_CHARS = 24_000

/** Сколько текста знаний вообще имеет смысл слать модели. Больше — деньги на
 *  ветер и переполненный контекст; лучше честно обрезать и сказать об этом. */
export const MAX_DOC_CHARS = 40_000
/** Сколько знаков хранит один документ знаний. */
export const MAX_SINGLE_DOC_CHARS = 200_000
/** Сколько документов принимаем из файла обмена: больше одному помощнику не нужно. */
export const MAX_IMPORT_DOCS = 20

/** Сколько единиц UTF-16 занимает знак, стоящий на этом месте строки. */
function charWidth(text: string, index: number): number {
  return (text.codePointAt(index) ?? 0) > 0xffff ? 2 : 1
}

/**
 * Сколько в строке знаков.
 *
 * ⚠️ Знак — это кодовая точка, а не единица UTF-16: эмодзи занимает в строке
 * две единицы, но это один знак. Так же считает сервер команды, и число «N
 * знаков», которое видит человек, обязано значить одно и то же по обе стороны.
 */
export function countChars(text: string): number {
  let count = 0
  for (let index = 0; index < text.length; index += charWidth(text, index)) count += 1
  return count
}

/**
 * Первые `max` знаков строки.
 *
 * ⚠️ Режем по знакам, а не `slice` по единицам UTF-16: граница, попавшая на
 * середину эмодзи, оставляла в конце текста его половину — одинокий суррогат,
 * который на диске и у модели превращается в «�».
 */
export function cutChars(text: string, max: number): string {
  // Знаков не бывает больше, чем единиц UTF-16: короткую строку мерить незачем.
  if (text.length <= max) return text
  let index = 0
  for (let count = 0; count < max && index < text.length; count += 1) index += charWidth(text, index)
  return text.slice(0, index)
}
