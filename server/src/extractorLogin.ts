/**
 * Площадка закрыла анонимный доступ — материал отдают только тем, кто вошёл в
 * аккаунт.
 *
 * ⚠️ Это НЕ «битая ссылка» и НЕ «публикация недоступна», а прежнее сообщение
 * говорило именно так и посылало человека искать несуществующую беду. Проверено
 * 18.09.2026 на публичном ролике Vimeo (vimeo.com/315204505, страница отдаётся с
 * кодом 200, oEmbed показывает название и автора): и наш yt-dlp 2026.08.19 —
 * самый свежий выпуск, — и ночная сборка 2026.09.16 отвечают «The web client
 * only works when logged-in», клиент `android` требует ранее сохранённых
 * токенов, а конфигурация плеера отвечает 403 и встраивание 401. Через прокси
 * ровно то же самое, значит дело не в нашей сети и не в устаревшем extractor'е:
 * доскачать тут нечего, пока нет входа в аккаунт.
 *
 * ⚠️ Признак узкий НАМЕРЕННО: «Private video» и прочие отказы по конкретной
 * публикации сюда НЕ входят — там прежнее «проверьте ссылку и доступность
 * публикации» как раз верно, и подменять его словами про вход значило бы уводить
 * человека в другую сторону. Ловим только стену входа на всей площадке.
 */
export const EXTRACTOR_LOGIN_SIGNATURE =
  /only works when logged.?in|account credentials|--cookies-from-browser|sign in to confirm|login required|requires? (?:a )?(?:login|account)/i

/** Отличает «нужен вход» от прочих отказов extractor'а по его же выводу. */
export function needsExtractorLogin(text: string): boolean {
  return EXTRACTOR_LOGIN_SIGNATURE.test(text)
}
