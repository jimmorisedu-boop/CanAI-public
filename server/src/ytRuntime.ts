// JS-движок для yt-dlp.
//
// С 2026 года YouTube требует исполнять свой JavaScript, чтобы отдать форматы.
// Без движка yt-dlp честно предупреждает («No supported JavaScript runtime
// could be found») и извлекает что придётся: замер 18.08.2026 на живой ссылке —
// БЕЗ движка доступен только формат 18 (360p), С движком — 96 (1080p). А на
// части роликов подходящего формата не остаётся вовсе, и скачивание падает:
// отсюда жалоба «не все ссылки скачиваются».
//
// По умолчанию yt-dlp ищет только deno, которого у нас нет. Зато ВСЕГДА есть
// Node — на нём работает сам сервер, и в дистрибутиве он лежит рядом
// (runtime/node). Поэтому просто показываем yt-dlp на него: качать ещё один
// портативный компонент ради того, что уже есть, незачем.
//
// Путь передаётся отдельным аргументом массива, поэтому пробелы в нём
// («C:\Program Files\nodejs») ничего не ломают.
export function jsRuntimeArgs(): string[] {
  return ['--js-runtimes', `node:${process.execPath}`]
}
