import { EnvHttpProxyAgent, setGlobalDispatcher } from 'undici'
import { proxyForUrl, type ProxyEnv } from './proxyConfig.js'

/**
 * Пустить исходящие HTTP-запросы через прокси, если он задан.
 *
 * ⚠️ **`fetch` в Node прокси САМ НЕ УМЕЕТ.** Переменные `HTTPS_PROXY`/
 * `HTTP_PROXY` он не читает: их знают curl и браузеры, а undici — нет, пока ей
 * явно не дали диспетчер. Из-за этого получалось наполовину рабочее
 * состояние, которое ни на что не похоже: WebSocket доски прокси уважал
 * (`proxyAgentFor`), а КАЖДЫЙ обычный запрос к серверу команды — вход, список
 * моделей, запуск генерации, загрузка файлов — уходил напрямую. У человека за
 * VPN это выглядит как «доска то работает, то нет» без всякой системы.
 *
 * `EnvHttpProxyAgent` читает те же переменные, что и остальной проект
 * (включая `NO_PROXY`), поэтому настройка одна на всё приложение.
 *
 * ⚠️ Ставим диспетчер ТОЛЬКО когда прокси действительно задан: подменять
 * глобальный транспорт без нужды — значит менять поведение сети у всех, кто
 * никакого прокси не просил.
 */
/**
 * Насколько держать открытым соединение к серверу команды.
 *
 * ⚠️ **Каждое НОВОЕ соединение через прокси стоит около секунды** — это
 * CONNECT плюс шифрование, и платить их приходится заново, как только пул
 * закрыл соединение. По умолчанию undici держит его 4 секунды, то есть
 * практически каждый запрос к серверу команды получался холодным. Замер
 * 09.09.2026 на живом сервере через прокси: первый запрос 1054 мс, следом
 * 1033, после 6 секунд простоя снова 1049; с этой настройкой после 6 секунд
 * 306 мс, после 20 секунд 307 мс.
 *
 * ⚠️ Настройка нужна ОБЕИМ дорогам — и прямой, и через прокси, — поэтому
 * живёт здесь одна на всех: `cloudRoute` пересобирает диспетчер при каждой
 * смене дороги и берёт её отсюда же.
 */
export const CLOUD_KEEP_ALIVE = {
  keepAliveTimeout: 60_000,
  keepAliveMaxTimeout: 600_000,
} as const

export function applyProxyDispatcher(env: ProxyEnv = process.env): string | null {
  // Проверяем на живом адресе: так учитываются и NO_PROXY, и разделение
  // http/https, а не просто «переменная не пустая».
  const probe = proxyForUrl('https://example.invalid/', env)
  if (!probe) return null
  setGlobalDispatcher(new EnvHttpProxyAgent(CLOUD_KEEP_ALIVE))
  return probe
}
