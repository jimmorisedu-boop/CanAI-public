import { spawnSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const workspaces = ['client', 'server']
const licenseOverrides = new Map([
  ['robot3', 'robot3.txt'],
  ['cookie-signature', 'cookie-signature.txt'],
  ['isarray', 'isarray.txt'],
  // Движок сравнения лиц: MIT, но файла лицензии в npm-пакете нет —
  // берём официальный текст из репозитория Microsoft.
  ['onnxruntime-web', 'onnxruntime.txt'],
  ['onnxruntime-common', 'onnxruntime.txt'],
  ['guid-typescript', 'guid-typescript.txt'],
])

function licenseOverrideFor(packageName, version) {
  if (packageName.startsWith('@esbuild/')) return 'esbuild.txt'
  // Платформенные keyring-бинарники публикуются отдельно и не включают
  // LICENSE, хотя родительский upstream-пакет и весь репозиторий имеют MIT.
  if (packageName.startsWith('@napi-rs/keyring-') && version === '1.2.0') {
    return 'napi-rs-keyring.txt'
  }
  // Бинарные @img/sharp-libvips-* намеренно публикуются без LICENSE/NOTICE.
  // Notices зависят от состава сборки, поэтому новую версию нужно проверить
  // и явно добавить в этот список вместе с актуальным upstream-файлом.
  if (packageName.startsWith('@img/sharp-libvips-') && (version === '1.3.3' || version === '1.3.4')) {
    return 'sharp-libvips.txt'
  }
  // Начиная с sharp 0.35 Windows-пакет объединяет addon и DLL libvips.
  // В 0.35.4 внутри sharp-libvips 1.3.3, в 0.35.5 — 1.3.4, поэтому
  // им нужен тот же полный LGPL/GPL bundle и официальный
  // список встроенных библиотек.
  if (
    packageName.startsWith('@img/sharp-win32-') &&
    (version === '0.35.4' || version === '0.35.5')
  ) {
    return 'sharp-libvips.txt'
  }
  return licenseOverrides.get(packageName)
}

function productionPackageDirs(workspace) {
  const cwd = path.join(root, workspace)
  const command = process.platform === 'win32' ? (process.env.ComSpec || 'cmd.exe') : 'npm'
  const args = process.platform === 'win32'
    ? ['/d', '/s', '/c', 'npm ls --omit=dev --all --parseable']
    : ['ls', '--omit=dev', '--all', '--parseable']
  const result = spawnSync(command, args, {
    cwd,
    encoding: 'utf8',
  })
  if (result.status !== 0) {
    throw new Error(`npm ls failed in ${workspace}: ${result.stderr || result.stdout}`)
  }
  return result.stdout
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && path.resolve(line) !== cwd)
}

function licenseName(value) {
  if (typeof value === 'string') return value
  if (value && typeof value === 'object' && typeof value.type === 'string') return value.type
  if (Array.isArray(value)) return value.map(licenseName).filter(Boolean).join(' OR ')
  return 'UNKNOWN'
}

function repositoryUrl(value) {
  if (typeof value === 'string') return value
  if (value && typeof value === 'object' && typeof value.url === 'string') return value.url
  return null
}

function packageLicenseFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && /^(licen[cs]e|copying|notice)(?:[-_.].*)?$/i.test(entry.name))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b))
}

function normalizeText(text) {
  return text.replace(/\r\n?/g, '\n').replace(/[ \t]+$/gm, '').trim()
}

const packages = new Map()
for (const workspace of workspaces) {
  for (const dir of productionPackageDirs(workspace)) {
    const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'))
    if (!manifest.name || !manifest.version || manifest.private) continue
    const key = `${manifest.name}@${manifest.version}`
    if (packages.has(key)) continue
    const files = packageLicenseFiles(dir)
    const override = licenseOverrideFor(manifest.name, manifest.version)
    if (files.length === 0 && !override) {
      throw new Error(`${key}: license/notice file is missing in ${dir}`)
    }
    const texts = files.map((name) => ({ name, text: normalizeText(fs.readFileSync(path.join(dir, name), 'utf8')) }))
    if (override) {
      texts.push({
        name: 'LICENSE (upstream copy; omitted from npm package)',
        text: normalizeText(fs.readFileSync(path.join(root, 'scripts', 'license-overrides', override), 'utf8')),
      })
    }
    packages.set(key, {
      key,
      license: licenseName(manifest.license ?? manifest.licenses),
      source: repositoryUrl(manifest.repository) ?? manifest.homepage ?? 'not specified',
      texts,
    })
  }
}

const sorted = [...packages.values()].sort((a, b) => a.key.localeCompare(b.key))
const lines = [
  'CanAI — third-party production dependency licenses',
  'Generated by scripts/generate-third-party.mjs from installed production packages.',
  'Do not edit this file manually.',
  '',
  `Packages: ${sorted.length}`,
  '',
]

for (const entry of sorted) {
  lines.push('='.repeat(80))
  lines.push(`PACKAGE: ${entry.key}`)
  lines.push(`DECLARED LICENSE: ${entry.license}`)
  lines.push(`SOURCE: ${entry.source}`)
  for (const item of entry.texts) {
    lines.push(`--- ${item.name} ---`)
    lines.push(item.text)
  }
  lines.push('')
}

// Путь вывода можно задать аргументом. По умолчанию — файл в корне, как и
// раньше: `npm run licenses` и make-dist зовут генератор без аргументов, и для
// них ничего не меняется. Аргумент нужен ТЕСТУ: он запускает настоящий
// генератор, а тот переписывал отслеживаемый git-ом файл прямо в репозитории.
// Список собирается из УСТАНОВЛЕННЫХ пакетов, а они платформенные — на macOS
// в файл уезжали darwin-сборки вместо win32, и такой файл нельзя отдавать
// покупателю на Windows.
const outFile = process.argv[2] ? path.resolve(process.argv[2]) : path.join(root, 'THIRD-PARTY-LICENSES.txt')
fs.writeFileSync(outFile, `${lines.join('\n').trimEnd()}\n`, 'utf8')
console.log(`[licenses] ${sorted.length} production packages documented`)
